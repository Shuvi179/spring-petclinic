#!/bin/bash
# Setup script for running spring-petclinic in Claude Code cloud sessions (claude.ai/code).
#
# Where it goes: claude.ai/code -> your environment -> "Setup script" (paste it or "Choose file").
# It is NOT run automatically from the repo; this copy is kept here for versioning.
#
# How it runs: as root on Ubuntu 24.04, before Claude Code starts. If it finishes within
# ~5 minutes, the VM filesystem is snapshotted and reused (~7 days), so downloaded Maven
# dependencies and Docker images are already on disk in later sessions. Running processes
# (dockerd) are NOT cached; scripts/claude-cloud/session-start.sh starts them per session.
#
# It must exit 0, otherwise the session fails to start, so every step is best-effort.

set -uo pipefail

log() { echo "[petclinic-setup] $*"; }
STEP_TIMEOUT=200 # seconds per long step; keeps the whole script under the ~5 min cache limit

# --- 1. Java ----------------------------------------------------------------------------
# The image ships OpenJDK 21; the project needs Java 17+.
if command -v java >/dev/null 2>&1; then
  log "java: $(java -version 2>&1 | head -1)"
else
  log "java missing, installing openjdk-21-jdk-headless"
  (apt-get update -qq && apt-get install -y -qq openjdk-21-jdk-headless) || log "WARN: java install failed"
fi

# --- 2. Proxy settings for Maven / Gradle -----------------------------------------------
# Outbound traffic goes through an HTTP(S) proxy. Maven and Gradle ignore HTTPS_PROXY,
# so translate it into their own config files.
configure_jvm_proxy() {
  local proxy="${HTTPS_PROXY:-${https_proxy:-${HTTP_PROXY:-${http_proxy:-}}}}"
  [ -n "$proxy" ] || { log "no proxy env var set, skipping Maven/Gradle proxy config"; return 0; }

  local rest="${proxy#*://}" userinfo="" user="" pass=""
  rest="${rest%%/*}"
  if [[ "$rest" == *@* ]]; then
    userinfo="${rest%@*}"; rest="${rest##*@}"
    user="${userinfo%%:*}"; [[ "$userinfo" == *:* ]] && pass="${userinfo#*:}"
  fi
  local host="${rest%:*}" port="${rest##*:}"
  [[ "$rest" == *:* ]] || port=80

  local no_proxy_raw="${NO_PROXY:-${no_proxy:-localhost,127.0.0.1}}" non_proxy="" h
  IFS=',' read -ra hosts <<< "$no_proxy_raw"
  for h in "${hosts[@]}"; do
    h="$(echo "$h" | xargs)"; [ -n "$h" ] || continue
    [[ "$h" == .* ]] && h="*$h"
    non_proxy="${non_proxy:+$non_proxy|}$h"
  done

  local home_dir="${HOME:-/root}"
  mkdir -p "$home_dir/.m2" "$home_dir/.gradle"

  local m2="$home_dir/.m2/settings.xml"
  if [ ! -f "$m2" ] || grep -q "generated by claude-cloud" "$m2"; then
    local auth=""
    [ -n "$user" ] && auth="<username>${user}</username><password>${pass}</password>"
    cat > "$m2" <<EOF
<!-- generated by claude-cloud setup: proxy from \$HTTPS_PROXY -->
<settings>
  <proxies>
    <proxy><id>https</id><active>true</active><protocol>https</protocol>
      <host>${host}</host><port>${port}</port>${auth}<nonProxyHosts>${non_proxy}</nonProxyHosts></proxy>
    <proxy><id>http</id><active>true</active><protocol>http</protocol>
      <host>${host}</host><port>${port}</port>${auth}<nonProxyHosts>${non_proxy}</nonProxyHosts></proxy>
  </proxies>
</settings>
EOF
    log "wrote $m2 (proxy ${host}:${port})"
  fi

  local gp="$home_dir/.gradle/gradle.properties"
  if [ ! -f "$gp" ] || grep -q "generated by claude-cloud" "$gp"; then
    {
      echo "# generated by claude-cloud setup: proxy from \$HTTPS_PROXY"
      for scheme in http https; do
        echo "systemProp.${scheme}.proxyHost=${host}"
        echo "systemProp.${scheme}.proxyPort=${port}"
        echo "systemProp.${scheme}.nonProxyHosts=${non_proxy}"
        [ -n "$user" ] && echo "systemProp.${scheme}.proxyUser=${user}" && echo "systemProp.${scheme}.proxyPassword=${pass}"
      done
    } > "$gp"
    log "wrote $gp"
  fi
}
configure_jvm_proxy || log "WARN: proxy config failed"

# --- 3. Docker daemon (temporary, only to pre-pull images) -------------------------------
start_dockerd() {
  docker info >/dev/null 2>&1 && return 0
  log "starting dockerd"
  nohup dockerd >/var/log/dockerd.log 2>&1 &
  for _ in $(seq 1 30); do docker info >/dev/null 2>&1 && return 0; sleep 1; done
  log "WARN: dockerd did not become ready, see /var/log/dockerd.log"; tail -20 /var/log/dockerd.log || true
  return 1
}

pull_images() {
  start_dockerd || return 0
  # Images used by MySqlIntegrationTests (Testcontainers) and PostgresIntegrationTests
  # (docker compose). Keep in sync with docker-compose.yml / MySqlIntegrationTests.java.
  local img
  for img in mysql:9.7 postgres:18.4; do
    timeout "$STEP_TIMEOUT" docker pull -q "$img" && log "pulled $img" || log "WARN: pull $img failed"
  done
}

# --- 4. Warm up the Maven repository ----------------------------------------------------
find_repo() {
  local d
  for d in "${CLAUDE_PROJECT_DIR:-}" "$PWD" /home/user/* /root/* /workspace/* /code/* /repo*; do
    [ -n "$d" ] && [ -f "$d/pom.xml" ] && grep -q "spring-petclinic" "$d/pom.xml" 2>/dev/null && { echo "$d"; return 0; }
  done
  find / -xdev -maxdepth 4 -name pom.xml -path "*petclinic*" 2>/dev/null | head -1 | xargs -r dirname
}

warm_maven() {
  local repo; repo="$(find_repo)"
  if [ -z "$repo" ]; then
    log "repo not found yet, skipping Maven warm-up (dependencies download on first build)"
    return 0
  fi
  log "warming Maven cache in $repo"
  cd "$repo" || return 0
  chmod +x mvnw 2>/dev/null || true
  # Compiles main + test code and resolves the plugins used by the normal build, without
  # running tests. Output is kept quiet; failures are only a warning.
  timeout "$STEP_TIMEOUT" ./mvnw -B -ntp -q -DskipTests test-compile >/tmp/petclinic-mvn-warmup.log 2>&1 \
    && log "Maven warm-up done" \
    || { log "WARN: Maven warm-up failed/timed out, tail of log:"; tail -20 /tmp/petclinic-mvn-warmup.log || true; }
}

# Image pulls and the Maven download are independent; run them in parallel.
pull_images &
warm_maven &
wait

# Stop the temporary daemon cleanly so the snapshot is consistent; the SessionStart hook
# starts it again in every session.
if pgrep -x dockerd >/dev/null 2>&1; then
  pkill -x dockerd || true
  for _ in $(seq 1 15); do pgrep -x dockerd >/dev/null 2>&1 || break; sleep 1; done
fi

log "done"
exit 0
